"""Leakage-free preprocessing pipelines using scikit-learn ColumnTransformer and Pipeline."""

from typing import List, Optional, Tuple
from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import MinMaxScaler, OneHotEncoder, RobustScaler, StandardScaler

from automl.profiler.schemas import DatasetProfile, DataType
from automl.trainer.schemas import (
    ImputationStrategy,
    PreprocessingConfig,
    ScalingStrategy,
)


def _get_scaler(scaling: ScalingStrategy):
    """Return configured scikit-learn scaler or None."""
    if scaling == ScalingStrategy.STANDARD:
        return StandardScaler()
    elif scaling == ScalingStrategy.MINMAX:
        return MinMaxScaler()
    elif scaling == ScalingStrategy.ROBUST:
        return RobustScaler()
    elif scaling == ScalingStrategy.NONE:
        return "passthrough"
    return StandardScaler()


def build_preprocessor(
    numeric_features: List[str],
    categorical_features: List[str],
    config: Optional[PreprocessingConfig] = None,
) -> ColumnTransformer:
    """Build a scikit-learn ColumnTransformer for numeric and categorical features.

    Fitting this transformer strictly inside a scikit-learn Pipeline guarantees
    zero data leakage between cross-validation folds or train/test splits.

    Args:
        numeric_features: Names of numerical columns.
        categorical_features: Names of categorical or boolean columns.
        config: Preprocessing configuration options.

    Returns:
        ColumnTransformer: Configured preprocessor.
    """
    cfg = config or PreprocessingConfig()

    transformers = []

    # 1. Numerical pipeline
    if numeric_features:
        num_imputer_strategy = cfg.numeric_imputer.value
        num_imputer = SimpleImputer(strategy=num_imputer_strategy)
        scaler = _get_scaler(cfg.scaling)

        num_steps = [("imputer", num_imputer)]
        if scaler != "passthrough":
            num_steps.append(("scaler", scaler))

        numeric_pipeline = Pipeline(steps=num_steps)
        transformers.append(("numeric", numeric_pipeline, numeric_features))

    # 2. Categorical pipeline
    if categorical_features:
        cat_imputer_strategy = cfg.categorical_imputer.value
        if cat_imputer_strategy == ImputationStrategy.CONSTANT.value:
            cat_imputer = SimpleImputer(strategy="constant", fill_value="missing")
        else:
            cat_imputer = SimpleImputer(strategy="most_frequent")

        encoder = OneHotEncoder(
            handle_unknown=cfg.handle_unknown_categories,
            sparse_output=False,
        )

        categorical_pipeline = Pipeline(
            steps=[
                ("imputer", cat_imputer),
                ("encoder", encoder),
            ]
        )
        transformers.append(("categorical", categorical_pipeline, categorical_features))

    preprocessor = ColumnTransformer(
        transformers=transformers,
        remainder="drop",
        verbose_feature_names_out=False,
    )
    return preprocessor


def extract_feature_columns(
    profile: DatasetProfile,
    target_column: str,
) -> Tuple[List[str], List[str], List[str]]:
    """Segregate dataset features into numeric, categorical, and dropped columns based on profile.

    Columns identified as likely entity identifiers or the target itself are excluded from features.

    Args:
        profile: DatasetProfile generated by Phase 1 profiler.
        target_column: The prediction target column name.

    Returns:
        Tuple[List[str], List[str], List[str]]: (numeric_features, categorical_features, dropped_features)
    """
    numeric_features: List[str] = []
    categorical_features: List[str] = []
    dropped_features: List[str] = []

    for col_name, col_profile in profile.columns.items():
        if col_name == target_column:
            continue

        if col_profile.inferred_type == DataType.ID_LIKE:
            dropped_features.append(col_name)
        elif col_profile.inferred_type == DataType.NUMERIC:
            numeric_features.append(col_name)
        elif col_profile.inferred_type in (DataType.CATEGORICAL, DataType.BOOLEAN):
            categorical_features.append(col_name)
        else:
            # Datetime, text, or unsupported column types for initial tabular MVP
            dropped_features.append(col_name)

    return numeric_features, categorical_features, dropped_features
